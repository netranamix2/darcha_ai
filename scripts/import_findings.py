"""Convert the researchers' spreadsheet (the master file) into the formats the backend uses.

    backend/.venv/bin/python scripts/import_findings.py path/to/data.xlsx

Writes:
  data/registry.yaml                  every document from the "База знаний" sheet (the master list)
  data/eval/questions.jsonl           test set (synthetic) + real questions (answerable / must-refuse)
  data/eval/harmful.jsonl             harmful messages with category and expected behaviour
  data/documents/faq/*.txt + meta.yaml  ready answers, one FAQ document per legal basis
  data/comments/private/comments.jsonl  real comments, PII-masked; git-ignored, never committed

Then run scripts/fetch_lex.py to download the full texts listed in the registry.
"""
from __future__ import annotations

import json
import re
import sys
from collections import defaultdict
from datetime import date, datetime
from pathlib import Path

import openpyxl
import yaml

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "backend"))
from app.kb.translit import detect_script, guess_language, mask_pii  # noqa: E402

STATUS = {   # sheet status -> registry status
    "Действует": "active", "Проверить": "check", "Отменено": "repealed",
    "Официальный FAQ": "faq", "Официальная статистика": "reference", "Разовое решение": "temporary",
}
LANG = {"узбекский": "uz", "русский": "ru", "смешанный": "mixed", "английский": "en"}
SCRIPT = {"латиница": "latin", "кириллица": "cyrillic", "смешанное": "mixed"}
ACTION = {"Ответить": "answer", "Передать специалисту (тикет)": "ticket"}


def rows(wb, name: str) -> list[tuple]:
    return [r for r in list(wb[name].iter_rows(values_only=True))[1:] if r and r[0] not in (None, "")]


def iso(d) -> str | None:
    if d in (None, "", "—"):
        return None
    if isinstance(d, (datetime, date)):
        return d.strftime("%Y-%m-%d")
    m = re.match(r"(\d{1,2})\.(\d{1,2})\.(\d{4})", str(d).strip())
    return f"{m[3]}-{int(m[2]):02d}-{int(m[1]):02d}" if m else None


def clean_number(raw: str, kind: str) -> str:
    """'рег. №2431-5 (приказ №443 от 11.11.2025)' -> '2431-5'; 'ПКМ №578' / '578' -> '578'; 'УП-222' stays."""
    s = re.sub(r"\(.*?\)", "", str(raw or "")).strip()
    s = re.sub(r"^(рег\.?|ПКМ|VMQ)\s*", "", s, flags=re.I).replace("№", "").strip()
    return "" if s in ("—", "-", "уточнить") or s.startswith("gov.uz") else s


def kb_number_index(registry: list[dict]) -> dict[str, str]:
    """digits of a number -> KB id, to map 'Постановление КМ №578 от 13.09.2025' to KB-001."""
    idx = {}
    for d in registry:
        if d["number"]:
            idx.setdefault(re.sub(r"\D", "", d["number"].split("(")[0]) or d["number"], d["id"])
    return idx


def basis_to_kb(text: str, idx: dict[str, str]) -> str | None:
    m = re.search(r"№\s*(?:рег\.\s*№)?\s*([A-ZА-Я]*-?\d[\d-]*)", str(text or ""))
    if not m:
        return None
    return idx.get(re.sub(r"\D", "", m[1]))


def main(xlsx: str) -> None:
    wb = openpyxl.load_workbook(xlsx, data_only=False)

    # ------------------------------------------------------------------ registry (master list)
    registry = []
    for r in rows(wb, "База знаний"):
        id_, title, kind, number, issued, status, topics, points, link, note, how = (list(r) + [None] * 11)[:11]
        st = STATUS.get(str(status).strip(), "check")
        doc = {
            "id": id_, "title": str(title).strip(), "kind": kind, "number": clean_number(number, kind),
            "number_raw": number, "issued_at": iso(issued), "status": st, "topics": topics,
            "key_points": points, "source_url": link or None, "status_note": note, "verified": how,
            "lex_url": link if link and "lex.uz" in str(link) else None,
        }
        if st == "temporary":
            # e.g. KB-025 "extended until 1.11.2026": stop citing it after that date
            m = re.search(r"до\s+(\d{1,2}\.\d{1,2}\.\d{4})", f"{points} {title}")
            doc["valid_until"] = iso(m[1]) if m else None
        registry.append(doc)
    (ROOT / "data").mkdir(exist_ok=True)
    (ROOT / "data/registry.yaml").write_text(
        "# Master list of documents, generated by scripts/import_findings.py from the researchers' spreadsheet.\n"
        "# status: active | check (not yet verified) | repealed (stop-list, never cited) | faq | reference | temporary\n"
        + yaml.safe_dump(registry, allow_unicode=True, sort_keys=False, width=200), encoding="utf-8")
    idx = kb_number_index(registry)
    by_id = {d["id"]: d for d in registry}

    # ------------------------------------------------------------------ eval questions
    out = []
    for r in rows(wb, "Тестовый набор"):
        id_, q, lang, script, topic, action, answer, basis, kb_ids = (list(r) + [None] * 9)[:9]
        kb = [k for k in re.findall(r"KB-\d+", str(kb_ids or ""))]
        row = {"id": id_, "source": "synthetic", "q": str(q).strip(), "lang": LANG.get(lang, lang),
               "script": SCRIPT.get(script, script), "topic": topic,
               "expected_action": ACTION.get(action, "answer"),
               "expected_points": [p.strip() for p in str(answer or "").split(";") if p.strip()]}
        if kb and by_id.get(kb[0], {}).get("number"):
            row["expected_doc"] = by_id[kb[0]]["number"]
            row["expected_kb"] = kb
        out.append(row)
    n_syn = len(out)
    for r in rows(wb, "Реальные вопросы"):
        id_, q, src_type, src, when, topic, covered, basis, note = (list(r) + [None] * 9)[:9]
        q = str(q).strip()
        row = {"id": id_, "source": "real", "source_type": src_type, "source_url": src, "q": q,
               "lang": guess_language(q), "script": detect_script(q), "topic": topic, "kb_covers": covered,
               "note": note}
        if covered == "Да":
            row["expected_action"] = "answer"
        elif covered == "Нет":
            row["expected_action"] = "refuse"   # the KB has no basis: must not be auto-answered
        kb = basis_to_kb(basis, idx)
        if kb and by_id[kb]["number"]:
            row["expected_doc"] = by_id[kb]["number"]
            row["expected_kb"] = [kb]
        out.append(row)
    (ROOT / "data/eval").mkdir(parents=True, exist_ok=True)
    (ROOT / "data/eval/questions.jsonl").write_text(
        "\n".join(json.dumps(x, ensure_ascii=False) for x in out) + "\n", encoding="utf-8")

    # ------------------------------------------------------------------ harmful (merge with the existing set)
    hpath = ROOT / "data/eval/harmful.jsonl"
    existing = [json.loads(x) for x in hpath.read_text(encoding="utf-8").splitlines() if x.strip()] if hpath.exists() else []
    seen = {h["q"].strip().lower() for h in existing}
    added = 0
    for r in rows(wb, "Вредные сообщения"):
        id_, msg, lang, cat, expected, green_ok = (list(r) + [None] * 6)[:6]
        if str(msg).strip().lower() in seen:
            continue
        existing.append({"id": id_, "q": str(msg).strip(), "lang": LANG.get(lang, lang), "category": cat,
                         "expected": expected})
        added += 1
    hpath.write_text("\n".join(json.dumps(x, ensure_ascii=False) for x in existing) + "\n", encoding="utf-8")

    # ------------------------------------------------------------------ FAQ -> one document per legal basis
    faq_dir = ROOT / "data/documents/faq"
    faq_dir.mkdir(parents=True, exist_ok=True)
    groups: dict[str, list] = defaultdict(list)
    for r in rows(wb, "Готовые ответы (FAQ)"):
        id_, q, lang, answer, basis, src = (list(r) + [None] * 6)[:6]
        groups[basis_to_kb(basis, idx) or "other"].append((id_, q, answer, src))
    faq_meta = []
    for kb, items in sorted(groups.items()):
        d = by_id.get(kb)
        if d and d["status"] in ("repealed",):
            print(f"  ! FAQ on repealed {kb} skipped")
            continue
        name = f"faq_{kb.lower()}.txt"
        lines = [f"S: {q}\nJ: {a}\n" for _, q, a, _ in items]
        (faq_dir / name).write_text("\n".join(lines), encoding="utf-8")
        faq_meta.append({
            "file": name, "title": f"Tez-tez beriladigan savollar — {d['title'] if d else 'boshqa'}",
            "number": d["number"] if d else None, "issued_at": d["issued_at"] if d else None, "status": "active",
            "source_url": (d or {}).get("lex_url") or items[0][3], "lang": "uz", "doc_type": "faq",
            "faq_ids": [i for i, *_ in items],
        })
    (faq_dir / "meta.yaml").write_text(
        "# Generated by scripts/import_findings.py from the 'Готовые ответы (FAQ)' sheet.\n"
        + yaml.safe_dump(faq_meta, allow_unicode=True, sort_keys=False, width=200), encoding="utf-8")

    # ------------------------------------------------------------------ comments (private, PII-masked)
    cdir = ROOT / "data/comments/private"
    cdir.mkdir(parents=True, exist_ok=True)
    comments, masked_total = [], 0
    ws = wb["Комментарии (шаблон)"]
    for r in list(ws.iter_rows(values_only=True))[1:]:
        texts = [str(c).strip() for c in r[3:] if c not in (None, "")]   # col D, plus anything stuck in E+
        for t in texts:
            t2, found = mask_pii(t)
            t2 = re.sub(r"@[A-Za-z0-9_.]{3,}", "[USERNAME]", t2)
            masked_total += sum(len(v) for v in found.values()) + (t2.count("[USERNAME]"))
            comments.append({"platform": str(r[1] or "unknown").lower(), "channel": r[2], "text": t2})
    (cdir / "comments.jsonl").write_text("\n".join(json.dumps(c, ensure_ascii=False) for c in comments) + "\n",
                                          encoding="utf-8")

    # ------------------------------------------------------------------ report
    cnt = defaultdict(int)
    for d in registry:
        cnt[d["status"]] += 1
    print(f"registry: {len(registry)} documents {dict(cnt)}")
    print(f"questions: {n_syn} synthetic + {len(out) - n_syn} real "
          f"({sum(x.get('expected_action') == 'refuse' for x in out)} must-refuse)")
    print(f"harmful: {len(existing)} ({added} added from the sheet)")
    print(f"faq: {sum(len(v) for v in groups.values())} pairs in {len(faq_meta)} documents")
    print(f"comments: {len(comments)} (private, {masked_total} PII items masked)")


if __name__ == "__main__":
    main(sys.argv[1])
